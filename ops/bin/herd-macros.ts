#!/usr/bin/env bun
// Generate herd.yaml flag macros from the llama-server binaries on this box.
//
//   ops/bin/herd-macros.ts --check     # exit 1 if the block is stale
//   ops/bin/herd-macros.ts --write     # regenerate in place
//   ops/bin/herd-macros.ts --divergence # per-fork flag differences only
//
// Why per-fork: there is not one llama-server. The estate carries four
// forks (beellama, ik_llama, llama-cpp-turboquant, upstream b11059) and
// their flag sets are NOT the same. A macro written from beellama's help can
// name a flag turboquant does not have, and vice versa, so a single-binary
// generator silently produces config that only works on one fork.
//
// Every flag any fork supports becomes an ARG_<FLAG> macro, annotated with
// the forks that actually accept it. Using a macro against a fork that
// lacks the flag fails at model load, loudly, which is the correct failure
// mode — a macro that silently expands to nothing is how REASONING_OFF and
// SPEC_NONE ended up defined as empty strings and left gemma-4 reasoning
// with the default --reasoning auto.
//
// This owns only its own marked block. Hand-written macros (MODEL_DIR,
// SRV_BASE, REASONING_OFF, the CTX_* bundles) are preserved untouched.

import { rename, rm } from "node:fs/promises";
import { parse } from "yaml";

const ENGINES = ["/home/toxic/estate/engines", "/home/toxic/engines"];
const CONFIG = "/home/toxic/estate/config/herd.yaml";

const BEGIN = "  # >>> AUTO_FLAGS (generated by ops/bin/herd-macros.ts) >>>";
const END = "  # <<< AUTO_FLAGS <<<";

type Flag = {
  /** The flag exactly as the binary spells it, e.g. "api-key". */
  raw: string;
  /** Macro-safe form of the same, e.g. "api_key" -> ARG_API_KEY. */
  name: string;
  takesValue: boolean;
  section: string;
};
type Fork = { label: string; binary: string; flags: Map<string, Flag> };

/** Turn a `--help` section heading into a stable macro-group name.
 *
 * llama-server prints `----- common params -----`,
 * `----- sampling params -----`, `----- example-specific params -----`.
 * Those headings are the only grouping the binary itself offers, so use
 * them rather than inventing a taxonomy that will drift.
 */
export function sectionNameFor(heading: string): string {
  const raw = heading.replace(/^-+|-+$/g, "").trim();
  return raw.replace(/\s+params?$/i, "").replace(/\s+/g, "_").toUpperCase() || "OTHER";
}

/** Pull long flags, their arity, and their help section out of `--help`.
 *
 * An option entry looks like:
 *
 *   -c,    --ctx-size N                     size of the prompt context ...
 *   --metrics                               enable prometheus metrics ...
 *   -fa,   --flash-attn [on|off|auto]       set Flash Attention use ...
 *
 * A value marker is N, PATH, TYPE, {a,b}, [on|off|auto] or VALUE sitting
 * immediately after the flag token. `(default:` does not count.
 */
export function parseFlags(help: string): Map<string, Flag> {
  const out = new Map<string, Flag>();
  let section = "OTHER";
  for (const raw of help.split("\n")) {
    // Two heading dialects: llama.cpp prints `----- common params -----`,
    // ik_llama prints a bare `general:` line.
    const dashed = raw.match(/^-----\s*(.+?)\s*-----\s*$/);
    const colon = raw.match(/^\s{0,4}([A-Za-z][A-Za-z0-9 _-]{0,40}):\s*$/);
    if (dashed) {
      section = sectionNameFor(dashed[1]);
      continue;
    }
    if (colon) {
      section = sectionNameFor(colon[1]);
      continue;
    }
    // Options are unindented in llama.cpp and indented two spaces in
    // ik_llama; both are options, wrapped description lines never start with
    // a dash.
    const line = raw.replace(/^\s+/, "");
    if (!/^-(?:-\S|[A-Za-z],|[A-Za-z]\s)/.test(line)) continue;
    const m = line.match(
      /--(?:no-)?([a-z0-9][a-z0-9-]*)(?:[ =](\{[^}]*\}|\[[^\]]*\]|[A-Z][A-Z0-9_]*))?/,
    );
    if (!m) continue;
    const flagName = m[1];
    const name = flagName.replace(/-/g, "_");
    if (out.has(name)) continue;
    out.set(name, { raw: flagName, name, takesValue: m[2] !== undefined, section });
  }
  return out;
}

/** Ask a binary for its --help, with whatever shared libraries it needs.
 *
 * The library directory is NOT always the binary's own directory. ik_llama
 * installs llama-server into build/bin but builds libllama.so into
 * build/src, libggml.so into build/ggml/src and libmtmd.so into
 * build/examples/mtmd, so a run without LD_LIBRARY_PATH fails with exit
 * 127 and the fork silently drops out of the union. Search the build tree
 * for the libraries instead of guessing one path.
 */
async function libraryDirsFor(binary: string): Promise<string> {
  const binDir = binary.slice(0, binary.lastIndexOf("/"));
  const buildRoot = binDir.slice(0, binDir.lastIndexOf("/"));
  const wanted = /^(libllama|libggml|libmtmd)\.so$/;
  const dirs = new Set<string>([binDir]);
  try {
    for await (const entry of new Bun.Glob("**/*.so").scan({
      root: buildRoot,
      absolute: true,
      onlyFiles: true,
    })) {
      const name = entry.slice(entry.lastIndexOf("/") + 1);
      if (wanted.test(name)) {
        dirs.add(entry.slice(0, entry.lastIndexOf("/")));
      }
    }
  } catch {
    // No build tree to scan; the binary's own directory is all we have.
  }
  return [...dirs].join(":");
}

/** Ask a binary for its --help, with whatever shared libraries it needs.
 *
 * The library directory is NOT always the binary's own directory. ik_llama
 * installs llama-server into build/bin but builds libllama.so into
 * build/src, libggml.so into build/ggml/src and libmtmd.so into
 * build/examples/mtmd, so a run without LD_LIBRARY_PATH fails with exit
 * 127 and the fork silently drops out of the union. Search the build tree
 * for the libraries instead of guessing one path.
 */
async function helpText(binary: string): Promise<string> {
  const ld = await libraryDirsFor(binary);
  const r = Bun.spawnSync([binary, "--help"], {
    env: { ...process.env, LD_LIBRARY_PATH: ld },
    stdout: "pipe",
    stderr: "pipe",
  });
  const out = r.stdout.toString();
  // ik_llama prints valid usage and then exits 1. Treat real usage text as
  // success; an empty stdout with a nonzero exit is a genuine failure.
  if (r.exitCode !== 0 && !out.includes("--")) {
    console.error(
      `skipping ${binary}: --help exited ${r.exitCode} with no usage text`,
    );
    return "";
  }
  if (!out.trim()) {
    console.error(`skipping ${binary}: --help produced no output`);
    return "";
  }
  return out;
}

async function discoverForks(): Promise<Fork[]> {
  const seen = new Set<string>();
  const found: string[] = [];
  for (const root of ENGINES) {
    for await (const entry of new Bun.Glob("**/llama-server").scan({
      root,
      absolute: true,
      onlyFiles: true,
    })) {
      if (!seen.has(entry)) {
        seen.add(entry);
        found.push(entry);
      }
    }
  }
  const forks: Fork[] = [];
  for (const binary of found.sort()) {
    const help = await helpText(binary);
    if (!help) continue;
    const label = binary
      .replace("/home/toxic/estate/engines/", "")
      .replace("/home/toxic/engines/", "")
      .replace(/\/llama-server$/, "")
      .replace(/\/llama-b\d+/, "");
    forks.push({ label, binary, flags: parseFlags(help) });
  }
  return forks;
}
function macroKey(name: string): string {
  return `ARG_${name.toUpperCase()}`;
}

/** Locate the generated block in a config, or null when it is absent. */
export function findBlock(text: string): string | null {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  return b >= 0 && e > b ? text.slice(b, e + END.length) : null;
}

/** Put the generated macros inside the `macros:` section.
 *
 * It has to land before `models:`, because that is where the macros block
 * ends in herd.yaml. Appending at end-of-file would park the macros under
 * the last model instead, where herd would silently ignore them.
 */
export function insertBlock(text: string, block: string): string | null {
  const existing = findBlock(text);
  if (existing) return text.replace(existing, block);
  const models = text.indexOf("\nmodels:");
  if (models < 0) return null;
  return `${text.slice(0, models)}\n${block}${text.slice(models)}`;
}

export function renderBlock(forks: Fork[]): string {
  const union = new Map<string, { flag: Flag; forks: string[] }>();
  for (const f of forks) {
    for (const [name, flag] of f.flags) {
      const entry = union.get(name) ?? { flag, forks: [] };
      // A flag that any fork documents as value-less stays value-less;
      // otherwise the union would emit a bare token that eats argv.
      entry.flag.takesValue = entry.flag.takesValue && flag.takesValue;
      entry.forks.push(f.label);
      union.set(name, entry);
    }
  }
  const names = [...union.keys()].sort();

  const lines = [BEGIN];
  lines.push(
    `  # ${names.length} flags, union across ${forks.length} llama-server forks:`,
    ...forks.map((f) => `  #   ${f.label} (${f.flags.size}) — ${f.binary}`),
    "  #",
    "  # Trailing forks list names only the forks that document that flag.",
    "  # Value-taking flags expand a ${<KEY>_VALUE} macro: define it in the",
    "  # macros above, or herd fails the load rather than silently consuming",
    "  # the next argv token.",
  );
  // Emit grouped by the help section each flag came from, so a 300-flag
  // wall stays navigable. Groups are ordered by size, descending.
  const groups = new Map<string, string[]>();
  for (const name of names) {
    const section = union.get(name)!.flag.section;
    const bucket = groups.get(section) ?? [];
    bucket.push(name);
    groups.set(section, bucket);
  }
  const ordered = [...groups.entries()].sort(
    (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]),
  );
  for (const [section, members] of ordered) {
    lines.push("", `  # --- ${section} (${members.length}) ---`);
    for (const name of members) {
      const { flag, forks: supporting } = union.get(name)!;
      const key = macroKey(name);
      // The flag keeps its real spelling (--api-key); only the macro key
      // is underscored (ARG_API_KEY).
      const value = flag.takesValue
        ? `"--${flag.raw} \${${key}_VALUE}"`
        : `"--${flag.raw}"`;
      const suffix =
        supporting.length === forks.length
          ? ""
          : `  # only: ${supporting.join(", ")}`;
      lines.push(`  ${key}: ${value}${suffix}`);
    }
  }
  lines.push(END);
  return lines.join("\n");
}

function reportDivergence(forks: Fork[]): number {
  const union = new Set<string>();
  for (const f of forks) for (const n of f.flags.keys()) union.add(n);
  console.log(`union: ${union.size} flags across ${forks.length} forks\n`);
  for (const f of forks) {
    const missing = [...union].filter((n) => !f.flags.has(n));
    console.log(`${f.label}: ${f.flags.size} flags, ${missing.length} missing`);
    for (const n of missing.sort()) console.log(`    -${n}`);
  }
  return 0;
}

async function main(): Promise<number> {
  const argv = process.argv.slice(2);
  let mode: "write" | "check" | "divergence" = "write";
  let config = CONFIG;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") mode = "check";
    else if (argv[i] === "--write") mode = "write";
    else if (argv[i] === "--divergence") mode = "divergence";
    else if (argv[i] === "--config") config = argv[++i];
    else {
      console.error(`unknown flag ${argv[i]}`);
      return 2;
    }
  }

  const forks = await discoverForks();
  if (forks.length === 0) {
    console.error(`no llama-server binaries found under ${ENGINES.join(", ")}`);
    return 1;
  }
  if (mode === "divergence") return reportDivergence(forks);

  const block = renderBlock(forks);
  const text = await Bun.file(config).text();
  const parsed = parse(text) as { macros?: Record<string, string> } | null;
  if (!parsed?.macros) {
    console.error(`${config} has no macros: section`);
    return 1;
  }

  const existing = findBlock(text);

  if (mode === "check") {
    if (existing === block) {
      console.error(`herd macros: in sync (${forks.length} forks)`);
      return 0;
    }
    console.error("herd macros: STALE. Run: ops/bin/herd-macros.ts --write");
    return 1;
  }

  const next = insertBlock(text, block);
  if (next === null) {
    console.error(`${config} has no top-level models: section to anchor on`);
    return 1;
  }

  // Everything not in the ARG_ namespace belongs to a human. The tool owns
  // the ARG_ prefix and its marked block, nothing else.
  const outside = new Map(
    Object.entries(parsed.macros).filter(([k]) => !k.startsWith("ARG_")),
  );
  return await writeNonDestructive(config, text, next, outside, forks.length);
}

/** Write only if nothing outside the generated block changed.
 *
 * The block is this tool's; everything else in the file belongs to a human.
 * The candidate is written to a temp file, parsed there, and only promoted
 * over the live config by rename. After the rename every macro outside the
 * ARG_ namespace is compared against the pre-write snapshot; any drift or
 * loss restores the original text and fails the run. A generator that can
 * silently eat hand-written config is worse than no generator.
 */
async function writeNonDestructive(
  config: string,
  originalText: string,
  nextText: string,
  outsideBefore: Map<string, string>,
  forkCount: number,
): Promise<number> {
  const tmp = `${config}.herd-macros.tmp`;
  const backup = `${config}.herd-macros.bak`;
  await Bun.write(tmp, nextText);

  let candidate: { macros?: Record<string, string> } | null = null;
  try {
    candidate = parse(await Bun.file(tmp).text()) as typeof candidate;
  } catch (e) {
    await rm(tmp, { force: true });
    console.error(`refusing to write: generated yaml does not parse (${e})`);
    return 1;
  }
  if (!candidate?.macros) {
    await rm(tmp, { force: true });
    console.error("refusing to write: generated yaml has no macros: section");
    return 1;
  }

  await Bun.write(backup, originalText);
  await rename(tmp, config);

  const after = parse(await Bun.file(config).text()) as {
    macros: Record<string, string>;
  };
  const drift: string[] = [];
  for (const [k, v] of outsideBefore) {
    const now = after.macros[k];
    if (now !== v) {
      drift.push(`${k}: ${JSON.stringify(v)} -> ${JSON.stringify(now)}`);
    }
  }
  const lost = [...outsideBefore.keys()].filter((k) => !(k in after.macros));
  if (drift.length || lost.length) {
    await Bun.write(config, originalText);
    console.error(
      `refusing to keep write: macros outside the generated block changed; restored ${config}`,
    );
    for (const d of drift) console.error(`  drifted ${d}`);
    for (const k of lost) console.error(`  lost ${k}`);
    return 1;
  }

  await rm(backup, { force: true });
  const count = Object.keys(after.macros).length;
  console.error(
    `wrote flag macros from ${forkCount} forks into ${config} (${count} macros total)`,
  );
  return 0;
}

if (import.meta.main) process.exit(await main());